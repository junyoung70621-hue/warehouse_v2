MAP_PATH = os.path.join(os.path.dirname(os.path.dirname(__file__)), "map.jpg")


def get_rack_map_image(rack_no: str, marker_size: int = 42) -> io.BytesIO | None:
    """
    map.jpg에 랙 위치 마커를 그린 이미지를 BytesIO로 반환.
    rack_no가 RACK_COORD에 없거나 map.jpg가 없으면 None 반환.
    """
    try:
        from PIL import Image, ImageDraw
    except ImportError:
        return None

    coord = RACK_COORD.get(rack_no)
    if not coord or not os.path.exists(MAP_PATH):
        return None

    x, y = coord
    img  = Image.open(MAP_PATH).convert("RGB")
    draw = ImageDraw.Draw(img)

    r_out = marker_size
    r_in  = marker_size // 2
    draw.ellipse([x - r_out, y - r_out, x + r_out, y + r_out],
                 fill=(220, 30, 30), outline=(140, 0, 0), width=4)
    draw.ellipse([x - r_in, y - r_in, x + r_in, y + r_in],
                 fill=(255, 255, 255))

    buf = io.BytesIO()
    img.save(buf, format="JPEG", quality=90)
    buf.seek(0)
    return buf
